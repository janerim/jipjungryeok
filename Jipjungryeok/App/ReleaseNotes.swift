import Foundation

/// §4.4 업데이트 안내에 쓰이는 버전별 변경 사항.
///
/// 서버에서 받아오지 않고 앱 안에 둔다. 이 앱은 네트워크 통신을 하지 않는 것이
/// 성격이고(§2), 릴리즈 노트 하나 때문에 서버를 두는 것은 앞뒤가 안 맞는다.
/// 빌드에 함께 나가므로 항상 그 버전의 내용과 일치한다.
///
/// **새 버전을 낼 때 여기에 항목을 추가한다.** 없으면 안내가 뜨지 않는다 —
/// 버그 수정만 있는 릴리즈는 굳이 알리지 않아도 되므로 그게 기본값이다.
enum ReleaseNotes {

    /// 버전 문자열(`CFBundleShortVersionString`)에 대응하는 변경 사항.
    private static let entries: [String: [String]] = [
        "1.2": [
            "집중 중에 화면 아래 중지 버튼이 생겼습니다. 끝까지 못 채워도 그때까지가 기록됩니다.",
            "중간에 멈추면 왜 멈췄는지 남길 수 있습니다. 비워 두어도 기록은 남습니다.",
            "기록 화면에서 지난 세션을 눌러 메모를 고칠 수 있습니다."
        ],
        "1.1": [
            "집중 시간이 끝난 뒤에도 계속 일했다면, 회고를 저장한 순간까지가 기록됩니다.",
            "업데이트가 있을 때 무엇이 바뀌었는지 알려 드립니다."
        ]
    ]

    static func notes(for version: String) -> [String] {
        entries[version] ?? []
    }
}
